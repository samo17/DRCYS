                            <p><b>¿Qué son las casas maternas?</b>
Espacios de hospedaje temporal: Son lugares donde las mujeres gestantes que viven lejos de los hospitales se alojan unos días antes del parto y unos días después, junto con un acompañante (hijos, pareja, familiar).</p>
<p> <b>Función principal:</b> No se atienden los partos en sí, sino que se cuida a la gestante y se la prepara para el parto, asegurando que esté cerca de un centro médico para una atención rápida cuando sea necesario.</p>
<p> <b>Objetivo:</b> Reducir la mortalidad y morbilidad materna y neonatal, especialmente en zonas rurales y remotas. </p>
<p> <b>¿Cómo interviene el SIS?</b></p>
<p><b>Financiamiento de la alimentación:</b> El SIS proporciona un monto diario para cubrir la alimentación de las gestantes y sus acompañantes, según lo aprobado por el seguro, para asegurarles una nutrición adecuada.</p>
<p><b>Cobertura integral:</b> Las gestantes afiliadas al SIS también tienen cobertura para sus controles prenatales, partos (normales o por cesárea), complicaciones y traslados de emergencia, incluyendo los aéreos o fluviales, detalla la Plataforma del Estado Peruano.</p>
<p><b>Coordinación: </b> El financiamiento se canaliza a través de las Direcciones Regionales de Salud (Disa) para la compra de los alimentos. </p>
